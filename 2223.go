package main

func sumScores(s string) int64 {
	z := zFunc(s)
	var ret int
	for _, v := range z {
		ret += v
	}
	ret += len(s)
	return int64(ret)
}

func zFunc(s string) []int {
	n := len(s)
	z := make([]int, n)
	l, r := 0, 0
	for i := 1; i < n; i++ {
		if i <= r {
			z[i] = min(z[i-l], r-i+1)
		}
		for i+z[i] < n && s[z[i]] == s[i+z[i]] {
			z[i]++
		}
		if i+z[i]-1 > r {
			l = i
			r = i + z[i] - 1
		}
	}
	return z
}
